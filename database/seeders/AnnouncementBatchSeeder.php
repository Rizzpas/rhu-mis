    /**
     * Run the database seeds to add 100 realistic RHU announcements.
     */
    public function run(): void
    {
        $this->command->info('📢 Seeding 100 realistic RHU announcements...');

        $announcementsData = $this->getAnnouncementsData();
        $createdCount = 0;
        $sectionsCount = 0;

        foreach ($announcementsData as $data) {
            $sections = $data['sections'] ?? [];
            unset($data['sections']);

            $announcement = Announcement::create($data);
            $createdCount++;

            if (!empty($sections)) {
                foreach ($sections as $index => $sec) {
                    AnnouncementImage::create([
                        'announcement_id' => $announcement->id,
                        'image_path'      => null,
                        'video_url'       => null,
                        'layout'          => $sec['layout'] ?? ($index % 2 === 0 ? 'left' : 'right'),
                        'media_type'      => 'image',
                        'content'         => $sec['content'],
                        'text_align'      => 'left',
                        'sort_order'      => $index + 1,
                        'type'            => 'section',
                        'created_at'      => $announcement->created_at,
                        'updated_at'      => $announcement->updated_at,
                    ]);
                    $sectionsCount++;
                }
            }
        }

        $this->command->info("✅ Successfully created {$createdCount} announcements with {$sectionsCount} dynamic sections!");
    }

